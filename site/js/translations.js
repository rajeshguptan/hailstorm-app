function changeLanguage(lang) {
  const t = window.translations[lang] || window.translations.en;
  document.querySelectorAll('[data-key]').forEach(el => {
    const key = el.getAttribute('data-key');
    const keys = key.split('.');
    let value = t;
    for (const k of keys) {
      value = value[k];
    }
    if (typeof value === 'string') {
      el.innerHTML = value;
    }
  });
  
  // Handle feature items
  document.querySelectorAll('.feature-item h3').forEach((el, i) => {
    if (t.features && t.features.items && t.features.items[i]) {
      el.innerHTML = t.features.items[i];
    }
  });
  document.querySelectorAll('.feature-item p').forEach((el, i) => {
    if (t.features && t.features.descriptions && t.features.descriptions[i]) {
      el.innerHTML = t.features.descriptions[i];
    }
  });
  
  // Handle license features
  document.querySelectorAll('.license-features').forEach((list, listIdx) => {
    const types = ['user', 'patron', 'developer'];
    const licenseType = types[listIdx];
    if (t.licenses && t.licenses[licenseType] && t.licenses[licenseType].features) {
      const items = list.querySelectorAll('li');
      items.forEach((item, i) => {
        if (t.licenses[licenseType].features[i]) {
          item.innerHTML = t.licenses[licenseType].features[i];
        }
      });
    }
  });
  
  document.documentElement.lang = lang;
  localStorage.setItem('preferred-lang', lang);
}

// Auto-detect browser language
function detectLanguage() {
  const browserLang = navigator.language.split('-')[0];
  const supportedLangs = ['en', 'es', 'fr', 'de', 'ja', 'zh', 'pt'];
  return supportedLangs.includes(browserLang) ? browserLang : 'en';
}